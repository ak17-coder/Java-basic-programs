public class LargestofThree
{
    public static void main(String[] args)
    {
        int num1 = 23;
        int num2 = 89;
        int num3 = 73;

        if(num1 > num2)
        {
            System.out.println("Num1 is greater");
        }
        else if(num2 > num3)
        {
            System.out.println("Num2 is greater");
        }
        else
        {
            System.out.println("Num3 is greater");
        }
    }
}
