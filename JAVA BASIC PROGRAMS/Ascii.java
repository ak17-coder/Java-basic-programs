public class Ascii
{
    public static void main(String[] args)
{

        //Char to ASCII Value
        char myChar1 = 'S';
        int myInt1 = (int) myChar1;
        System.out.println("ASCII Value : " + myInt1);

        //ASCII value to Char
        int myInt2 = 9;
        char myChar2 = (char) myInt2;
        System.out.println("Character Value : " + myChar2);

    }
}
