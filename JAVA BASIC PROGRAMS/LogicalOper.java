public class LogicalOper
{
    public static void main(String[] args)
    {
        int age = 18;
        System.out.println("Age = " + age);
        System.out.println("Logical operators");
        System.out.println("&& : " + (age >= 19 && age <= 60));
        System.out.println("|| : " + (age >= 19 || age <= 60));
        System.out.println("! : " + (!true));


    }
}
