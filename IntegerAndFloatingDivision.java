public class IntegerAndFloatingDivision
{
    public static void main(String[] args)
    {
        //1.Integer division using variables.
        int int1 = 10;
        int int2 = 5;
        int int3 = int1/int2;
        System.out.println("Integer division using variables : " + int3);

        //2.Integer division without using variables.
        System.out.println("Integer division without using variables : " + 10/5);

        //3.Float division using variables.
        int float1 = 20;
        int float2 = 6;
        float float3 = (float)float1/float2;
        System.out.println("Float division using variables : " + float3);

        //4.Float division without using variables.
        System.out.println("Float division without using variables : " + 6f/4);

    }
}
